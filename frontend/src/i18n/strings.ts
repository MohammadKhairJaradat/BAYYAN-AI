/** Interpolate {token} placeholders, e.g. fill(t.dashboard.sub, { year: 2025 }). */
export function fill(str: string, vars?: Record<string, string | number>): string {
  if (!str) return "";
  return str.replace(/\{(\w+)\}/g, (_, k: string) =>
    vars && k in vars ? String(vars[k]) : `{${k}}`
  );
}
